export type Copy = typeof zh;

/** How to install yt-dlp, ffmpeg, and gallery-dl on the OS that is actually running. */
export function toolInstallHint(locale: Locale): string {
  const win = process.platform === "win32";
  const mac = process.platform === "darwin";
  if (locale === "en") {
    if (win) {
      return "On Windows: winget install -e --id yt-dlp.yt-dlp && winget install -e --id yt-dlp.FFmpeg && winget install -e --id mikf.gallery-dl — or scoop install yt-dlp ffmpeg gallery-dl.";
    }
    if (mac) return "On Mac: brew install yt-dlp ffmpeg gallery-dl.";
    return "Install yt-dlp, ffmpeg, and gallery-dl and put them on PATH.";
  }
  if (win) {
    return "Windows 安装：winget install -e --id yt-dlp.yt-dlp，winget install -e --id yt-dlp.FFmpeg，winget install -e --id mikf.gallery-dl；或 scoop install yt-dlp ffmpeg gallery-dl。";
  }
  if (mac) return "Mac 安装：brew install yt-dlp ffmpeg gallery-dl。";
  return "请安装 yt-dlp、ffmpeg、gallery-dl，并加入 PATH。";
}

export function copy(locale: Locale): Copy {
  return locale === "en" ? en : zh;
}
